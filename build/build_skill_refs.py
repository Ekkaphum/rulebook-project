# -*- coding: utf-8 -*-
"""Generate the reference files for the `rulebook` skill from the research data."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data_kb import S, KB
from data_aux import PRAISED, CRITICISED, TEMPLATES, STYLE_RULES, CHECKLIST, METRICS

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   '.claude', 'skills', 'rulebook', 'references')
os.makedirs(OUT, exist_ok=True)

def cite(key):
    t, u = S[key]
    return f"[{t}]({u})"

def esc(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')

def write(name, text):
    p = os.path.join(OUT, name)
    with open(p, 'w', encoding='utf-8') as f:
        f.write(text.rstrip() + '\n')
    print(f"{name}: {os.path.getsize(p):,} B")

HEAD = ("<!-- Generated by build/build_skill_refs.py from the research corpus. "
        "Do not hand-edit; edit build/data_*.py and regenerate. -->\n\n")

# ---------------------------------------------------------------- style rules
by_area = {}
for area, rule, do, dont, key in STYLE_RULES:
    by_area.setdefault(area, []).append((rule, do, dont, key))
s = HEAD + "# Style rules\n\n"
s += ("26 rules distilled from professional rules editors and designer style guides. "
      "Apply them to every line of rules text.\n\n")
s += "| # | Area | Rule | Do | Don't | Source |\n|---|---|---|---|---|---|\n"
for i, (area, rule, do, dont, key) in enumerate(STYLE_RULES, 1):
    s += f"| {i} | {esc(area)} | {esc(rule)} | {esc(do)} | {esc(dont)} | {cite(key)} |\n"
write('style-rules.md', s)

# ----------------------------------------------------------------- checklist
phases = {}
for phase, item, why in CHECKLIST:
    phases.setdefault(phase, []).append((item, why))
s = HEAD + "# Pre-print checklist\n\n"
s += (f"{len(CHECKLIST)} items across {len(phases)} phases. Run the whole list before the "
      "files go to the printer. Report results phase by phase, quoting the failing line "
      "of the rulebook for each miss.\n\n")
for phase, items in phases.items():
    s += f"## {phase}\n\n"
    for item, why in items:
        s += f"- [ ] {item}\n      - *Why:* {why}\n"
    s += "\n"
write('checklist.md', s)

# ----------------------------------------------------------------- templates
s = HEAD + "# Section-order templates\n\n"
s += ("Ten published section orders. They agree on the spine — theme, goal, components, "
      "setup, overview, detail, end — and differ in how much reference apparatus they add. "
      "Pick the closest fit for the game's weight, then justify any departure.\n\n")
for name, sections in TEMPLATES.items():
    s += f"## {name}\n\n"
    for i, sec in enumerate(sections, 1):
        s += f"{i}. {sec}\n"
    s += "\n"
write('templates.md', s)

# ------------------------------------------------------------------ examples
s = HEAD + "# Worked examples: rulebooks the hobby praises and criticises\n\n"
s += ("Cite these by name when justifying a recommendation — a designer trusts "
      "'Fantasy Flight splits Learn to Play from Rules Reference' more than an abstract "
      "principle.\n\n## Praised\n\n")
s += "| Game / publisher | Aspect | What specifically | Source |\n|---|---|---|---|\n"
for g, a, w, k in PRAISED:
    s += f"| {esc(g)} | {esc(a)} | {esc(w)} | {cite(k)} |\n"
s += "\n## Criticised\n\n"
s += "| Game | Failure mode | What specifically | Source |\n|---|---|---|---|\n"
for g, a, w, k in CRITICISED:
    s += f"| {esc(g)} | {esc(a)} | {esc(w)} | {cite(k)} |\n"
write('examples.md', s)

# ------------------------------------------------------------------- metrics
s = HEAD + "# Quantitative reference points\n\n"
s += "Use these instead of adjectives. Every number below is sourced.\n\n"
s += "| Metric | Value | Context | Source |\n|---|---|---|---|\n"
for m, v, c, k in METRICS:
    s += f"| {esc(m)} | {esc(v)} | {esc(c)} | {cite(k)} |\n"
write('metrics.md', s)

# --------------------------------------------------------------- knowledge base
cats = {}
for row in KB:
    cats.setdefault(row[1], []).append(row)
s = HEAD + "# Knowledge base\n\n"
s += (f"{len(KB)} findings in {len(cats)} categories, each traceable to a source. "
      "Read the category that matches the question rather than the whole file.\n\n")
s += "**Categories:** " + " · ".join(f"{c} ({len(v)})" for c, v in cats.items()) + "\n\n"
for cat, rows in cats.items():
    s += f"## {cat}\n\n"
    for rid, _c, topic, principle, detail, evidence, key in rows:
        s += f"### {rid} — {topic}\n\n**{principle}**\n\n{detail}\n\n"
        if evidence:
            s += f"> {evidence}\n\n"
        s += f"Source: {cite(key)}\n\n"
write('knowledge-base.md', s)

# ------------------------------------------------------------------- sources
s = HEAD + "# Source index\n\n"
s += f"{len(S)} primary sources behind this skill.\n\n| Key | Source | URL |\n|---|---|---|\n"
for k in sorted(S):
    t, u = S[k]
    s += f"| `{k}` | {esc(t)} | <{u}> |\n"
write('sources.md', s)
